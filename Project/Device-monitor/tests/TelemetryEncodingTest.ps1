function Text([int[]] $codePoints) {
    return -join [char[]] $codePoints
}

$page = Invoke-WebRequest -UseBasicParsing 'http://127.0.0.1:8001/telemetry' -ErrorAction Stop
$expectedTexts = @(
    (Text @(0x4D, 0x43, 0x55, 0x20, 0x0111, 0x00E3, 0x20, 0x6B, 0x1EBF, 0x74, 0x20, 0x6E, 0x1ED1, 0x69)),
    (Text @(0x43, 0x68, 0x1ECD, 0x6E, 0x20, 0x4D, 0x43, 0x55, 0x20, 0x0111, 0x1EC3, 0x20, 0x78, 0x65, 0x6D, 0x20, 0x74, 0x65, 0x6C, 0x65, 0x6D, 0x65, 0x74, 0x72, 0x79, 0x2E)),
    (Text @(0x43, 0x68, 0x1ECD, 0x6E, 0x20, 0x6D, 0x1ED9, 0x74, 0x20, 0x4D, 0x43, 0x55))
)

foreach ($text in $expectedTexts) {
    if (-not $page.Content.Contains($text)) {
        throw "Missing UTF-8 Vietnamese text: $text"
    }
}

if ($page.Content.Contains((Text @(0x4D, 0x43, 0x55, 0x20, 0x00C4)))) {
    throw 'Telemetry page still contains mojibake text.'
}

Write-Output 'TelemetryEncodingTest passed'
